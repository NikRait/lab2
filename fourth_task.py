text = input("Input text: ")

print(f"Lenght: {len(text)}") # Prints lenght of the text
print(f"Upper: {text.upper()}") # Prints text with uppercase
print(f"Lower: {text.lower()}") # Prints text with lowercase
print(f"First character: {text[0]}") # Prints first character in text
print(f"Last character: {text[-1]}") # Prints last character in text
print(f"Number of spaces: {text.count(" ")}") # Prints amount of spaces in text

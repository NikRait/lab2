firstNumber = float(input("Enter first number: "))
secondNumber = float(input("Enter second number: "))

print(f"Sum: {firstNumber + secondNumber}")
print(f"Difference : {firstNumber - secondNumber}")
print(f"Product: {firstNumber * secondNumber:.2f}") # :.2f makes only 2 numbers after comma
print(f"Division: {firstNumber / secondNumber:.2f}")
print(f"Integer Division: {firstNumber // secondNumber}")
print(f"Ostatok: {firstNumber % secondNumber}")
print(f"Power: {firstNumber ** secondNumber:.2f}")
